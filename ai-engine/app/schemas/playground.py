"""Request and response contracts for the interactive LLM playground."""

from pydantic import BaseModel, ConfigDict, Field
from uuid import UUID


class PromptRequest(BaseModel):
    """A direct LLM prompt, or a project-scoped RAG prompt when project_id is set."""

    model_config = ConfigDict(extra="forbid", populate_by_name=True)

    prompt: str = Field(
        ..., min_length=1,
        description="The prompt text to send to the selected LLM.",
        examples=["Explain how cosine similarity is used in retrieval-augmented generation."],
    )
    model: str = Field(
        default="llama3.2", min_length=1, max_length=100,
        description="The Ollama model name to use. The model must already be available to Ollama.",
        examples=["llama3.2"],
    )
    project_id: UUID | None = Field(
        default=None,
        alias="projectId",
        description="When supplied, retrieve document chunks for this project before answering.",
    )
    top_k: int = Field(default=5, alias="topK", ge=1, le=50)


class PromptResponse(BaseModel):
    """Generated text and basic execution timing."""

    response: str = Field(description="Text generated by the selected model.")
    latency_ms: float | None = Field(default=None, description="End-to-end generation time in milliseconds.")
